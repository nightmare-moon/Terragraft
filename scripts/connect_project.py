"""Register one NEW, state-free Terraform project with the local Terragraft server.

Requires Windows runner to be configured, and one matching project root.
Never changes existing Terraform state or preconfigured Terraform backends.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re
import sys
import urllib.error
import urllib.request

INSTALL = Path(__file__).resolve().parent.parent
WORKSPACE = re.compile(r'^[A-Za-z0-9][A-Za-z0-9_-]{0,95}$')


def read_key(path, key):
    for line in path.read_text(encoding='utf-8').splitlines():
        if line.startswith(key + '='):
            return line.split('=', 1)[1]
    raise ValueError(f'Missing configuration setting: {key}')


def validate_project(path, root):
    root = Path(root).resolve(strict=True)
    project = Path(path).resolve(strict=True)
    if not project.is_dir():
        raise ValueError('Project must be a directory')
    try:
        project.relative_to(root)
    except ValueError:
        raise ValueError(f'Project must be inside your configured projects root: {root}')
    return project


def check_safe_new_project(project):
    # We do not migrate state. Manual reconciliation is required for existing projects.
    conflicts = [project/'terraform.tfstate',project/'terraform.tfstate.backup',
                 project/'.terraform'/'terraform.tfstate']
    conflicts.extend(project.glob('*.tfstate'))
    if any(p.exists() for p in conflicts):
        raise ValueError('Existing Terraform state or backend metadata found; no automatic migration performed')
    source_files = sorted((*project.glob('*.tf'),*project.glob('*.tf.json')))
    if not source_files:
        raise ValueError('No Terraform files found. Use -Create for a NEW demo project, or create main.tf first')
    for file in source_files:
        contents = file.read_text(encoding='utf-8',errors='replace')
        if re.search(r'\bbackend\s*["\']', contents):
            raise ValueError('Existing backend block found. Refusing to replace or duplicate it')
    if (project/'backend.tf').exists():
        raise ValueError('backend.tf already exists. Refusing to overwrite it')
    return project/'backend.tf'


def backend_text(workspace, url='http://127.0.0.1:8080'):
    if not WORKSPACE.fullmatch(workspace):
        raise ValueError('Workspace requires letters, digits, underscore or hyphen')
    if url != 'http://127.0.0.1:8080':
        raise ValueError('This local-only build only supports the loopback server')
    target = url+'/state/'+workspace
    return f'''# Generated by Terragraft CONNECT-PROJECT.ps1; contains no secrets.
terraform {{
  backend "http" {{
    address        = "{target}"
    lock_address   = "{target}"
    unlock_address = "{target}"
    lock_method    = "LOCK"
    unlock_method  = "UNLOCK"
    retry_wait_min = 1
  }}
}}
'''


def register(base_url, token, name, workspace, runner_id, path, engine):
    body = json.dumps({'name':name,'workspace':workspace,'runner_id':runner_id,
                       'local_path':str(path),'engine':engine}).encode('utf-8')
    req = urllib.request.Request(base_url+'/api/projects',method='POST', data=body,
                    headers={'Authorization':'Bearer '+token,'Content-Type':'application/json'})
    with urllib.request.urlopen(req, timeout=15) as response:
        return json.load(response)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--path',required=True)
    parser.add_argument('--workspace',required=True)
    parser.add_argument('--name')
    parser.add_argument('--engine',choices=('terraform','tofu'),default='terraform')
    parser.add_argument('--create',action='store_true',help='Create a new demonstration .tf project if needed')
    args = parser.parse_args()
    config = json.loads((INSTALL/'.terragraft.local.json').read_text(encoding='utf-8'))
    root = Path(config['projects_root']).resolve(strict=True)
    incoming = Path(args.path)
    if args.create:
        # Resolve any existing parent/symlink BEFORE creating anything on disk.
        if not incoming.is_absolute():
            raise ValueError('Project path must be absolute')
        try:
            incoming.resolve(strict=False).relative_to(root)
        except ValueError:
            raise ValueError('Refusing to create a project outside your configured root')
        incoming.mkdir(parents=True, exist_ok=True)
        if not any(p.exists() for p in (incoming/'terraform.tfstate',
                                         incoming/'terraform.tfstate.backup',
                                         incoming/'.terraform'/'terraform.tfstate')) and not list(incoming.glob('*.tf')) and not list(incoming.glob('*.tf.json')):
            (incoming/'main.tf').write_text('''# Example resource: local Terraform data only; no cloud credentials needed.
resource "terraform_data" "hello" {
  input = "Managed by Terragraft"
}
output "message" { value = terraform_data.hello.output }
''',encoding='utf-8')
    project = validate_project(incoming,root)
    backend_file = check_safe_new_project(project)
    backend_file.write_text(backend_text(args.workspace),encoding='utf-8',newline='\n')
    token = read_key(INSTALL/'.env','TERRAGRAFT_ADMIN_TOKEN')
    try:
        result = register('http://127.0.0.1:8080',token,args.name or project.name,
                          args.workspace,config.get('runner_id','local-win11'),project,args.engine)
    except Exception:
        # Do not leave a local backend configuration in place if registration fails.
        backend_file.unlink(missing_ok=True)
        raise
    print('Project registered:',result['id'])
    print('Terraform project: ',project)
    print('Workspace:         ',args.workspace)
    print('Backend created:   ',backend_file)
    print('Open http://127.0.0.1:8080/console, then click Queue plan.')
    print('For manual Terraform commands, dot-source USE-TERRAGRAFT.ps1 in the current PowerShell session.')


if __name__=='__main__':
    try:
        main()
    except (ValueError,FileNotFoundError,urllib.error.URLError,urllib.error.HTTPError) as error:
        if isinstance(error,urllib.error.HTTPError):
            message = error.read().decode('utf-8',errors='replace')[:600]
            error = f'HTTP {error.code}: {message}'
        print('ERROR:',error,file=sys.stderr)
        raise SystemExit(1)
